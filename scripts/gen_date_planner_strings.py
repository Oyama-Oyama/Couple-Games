def esc(value):
    return (value.replace("\\", "\\\\")
                 .replace("'", "\\'")
                 .replace("&", "&amp;")
                 .replace("<", "&lt;")
                 .replace(">", "&gt;"))


def main():
    if len(DATA["values"]) != len(KEYS):
        print(f"KEY COUNT MISMATCH: keys={len(KEYS)} values={len(DATA['values'])}")
        return 1
    for lang, values in DATA.items():
        if len(values) != len(KEYS):
            print(f"MISMATCH in {lang}: {len(values)} vs {len(KEYS)}")
            return 1

    for lang, values in DATA.items():
        path = os.path.join(RES, lang, "strings.xml")
        text = io.open(path, encoding="utf-8").read()
        added = 0
        for key, value in zip(KEYS, values):
            if f'name="{key}"' in text:
                continue
            block = f'    <string name="{key}">{esc(value)}</string>\n'
            text = text.replace("</resources>", block + "</resources>")
            added += 1
        io.open(path, "w", encoding="utf-8").write(text)
        print(f"{lang}: +{added} strings")
    print("done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
